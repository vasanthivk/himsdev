/* ---------- EVENTING INFRASTRUCTURE ---------- */
CREATE TABLE evt.outbox (                             -- transactional outbox -> relay (poller or Debezium CDC) -> Azure Service Bus
    outbox_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    event_type        VARCHAR(100) NOT NULL,         -- e.g. PatientAdmitted
    event_version     SMALLINT NOT NULL DEFAULT (1),
    aggregate_type    VARCHAR(60)  NOT NULL,         -- e.g. adt.admission
    aggregate_id      BIGINT        NOT NULL,
    session_key       VARCHAR(60)  NULL,             -- Service Bus session id (patient / encounter) for ordering
    organization_id   INT NULL,
    branch_id         INT NULL,
    patient_id        BIGINT NULL,
    correlation_id    UUID NULL,
    payload_json      JSONB NOT NULL,         -- CloudEvents 'data'
    occurred_at       TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at      TIMESTAMPTZ(3)  NULL,
    publish_attempts  INT NOT NULL DEFAULT (0),
    last_error        VARCHAR(1000) NULL
);
CREATE INDEX IX_outbox_unpublished ON evt.outbox(published_at, outbox_id);

CREATE TABLE evt.inbox (                              -- idempotent consumer log
    message_id        VARCHAR(100) NOT NULL PRIMARY KEY,   -- CloudEvents id
    event_type        VARCHAR(100) NOT NULL,
    source_service    VARCHAR(60)  NOT NULL,
    received_at       TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at      TIMESTAMPTZ(3)  NULL,
    process_status    VARCHAR(20)  NOT NULL DEFAULT ('RECEIVED'),  -- RECEIVED, PROCESSED, FAILED, SKIPPED
    error_message     VARCHAR(1000) NULL
);

CREATE TABLE evt.saga_instance (                      -- long-running workflows coordinated by this service
    saga_instance_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    saga_type         VARCHAR(60)  NOT NULL,         -- e.g. DISCHARGE, ORDER_TO_CASH, CASHLESS_CLAIM
    business_key      VARCHAR(60)  NOT NULL,
    current_step      VARCHAR(60)  NOT NULL,
    state_json        JSONB NULL,
    saga_status       VARCHAR(20)  NOT NULL DEFAULT ('RUNNING'),  -- RUNNING, COMPLETED, COMPENSATING, FAILED
    started_at        TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ(3)  NULL,
    timeout_at        TIMESTAMPTZ(3)  NULL
);

/* =====================================================================================
   POSTGRESQL HOUSEKEEPING: row version + updated_at maintenance
   (replaces SQL Server ROWVERSION; row_ver is used for optimistic locking)
   ===================================================================================== */
CREATE SCHEMA IF NOT EXISTS util;

CREATE OR REPLACE FUNCTION util.bump_row_ver() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.row_ver := COALESCE(OLD.row_ver, 0) + 1;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION util.touch_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.row_ver    := COALESCE(OLD.row_ver, 0) + 1;
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END $$;

-- attach the trigger to every table that has a row_ver column
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.table_schema, c.table_name,
               EXISTS (SELECT 1 FROM information_schema.columns u
                        WHERE u.table_schema = c.table_schema AND u.table_name = c.table_name
                          AND u.column_name = 'updated_at') AS has_updated_at
          FROM information_schema.columns c
         WHERE c.column_name = 'row_ver'
           AND c.table_schema NOT IN ('pg_catalog', 'information_schema')
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_row_ver ON %I.%I', r.table_schema, r.table_name);
        EXECUTE format('CREATE TRIGGER trg_row_ver BEFORE UPDATE ON %I.%I FOR EACH ROW EXECUTE FUNCTION %s',
                       r.table_schema, r.table_name,
                       CASE WHEN r.has_updated_at THEN 'util.touch_audit()' ELSE 'util.bump_row_ver()' END);
    END LOOP;
END $$;
