/* =====================================================================================
   DR REDDIS HEALTHCARE - HIMS MICROSERVICE DATABASE
   Service      : 04. Imaging (RIMS + PACS)
   Database     : hims_imaging   (PostgreSQL 15+ / EDB Postgres Advanced Server / Azure Database for PostgreSQL Flexible Server)
   Derived from : DrReddis_HIMS_Enterprise_Data_Model_PostgreSQL.sql (enterprise logical model)
   -------------------------------------------------------------------------------------
   Responsibility:
     RIMS: radiology procedures, modalities, scheduling, protocol, contrast & dose tracking, structured/voice reporting; PACS index over Azure Health Data Services DICOM: studies, series, annotations, AI findings, tele-radiology assignment, share links.
   Owned tables  : 13   | Replica / read-model tables in schema ref: 11
   Events PUBLISHED (Azure Service Bus topic 'hims.imaging'):
     StudyScheduled, StudyAcquired, RadReportFinalised, CriticalFindingDetected, AIFindingAvailable, RadProcedureUpdated
   Events SUBSCRIBED:
     OrderPlaced, OrderCancelled, PatientUpdated, DicomStudyReceived, ServiceUpdated, PractitionerUpdated
   Rules:
     - Only this service writes to the owned tables below. Other services read via API or events.
     - Foreign keys to data owned by other services are removed and marked 'logical FK'.
       Integrity is enforced by the application (validate id via API / replica at write time).
     - ref.* tables are local, eventually consistent copies filled by event handlers.
       Never write to them from business code; never enforce FKs against them.
     - Every state change writes a row to evt.outbox in the SAME transaction (transactional outbox).
     - Every consumed message is recorded in evt.inbox for idempotent processing.
   ===================================================================================== */

