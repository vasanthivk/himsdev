/* =====================================================================================
   POSTGRESQL HOUSEKEEPING: row version + updated_at maintenance
   (replaces SQL Server ROWVERSION; row_ver is used for optimistic locking)
   ===================================================================================== */
CREATE SCHEMA IF NOT EXISTS util;

CREATE OR REPLACE FUNCTION util.bump_row_ver() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.row_ver := COALESCE(OLD.row_ver, 0) + 1;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION util.touch_audit() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.row_ver    := COALESCE(OLD.row_ver, 0) + 1;
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END $$;

-- attach the trigger to every table that has a row_ver column
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.table_schema, c.table_name,
               EXISTS (SELECT 1 FROM information_schema.columns u
                        WHERE u.table_schema = c.table_schema AND u.table_name = c.table_name
                          AND u.column_name = 'updated_at') AS has_updated_at
          FROM information_schema.columns c
         WHERE c.column_name = 'row_ver'
           AND c.table_schema NOT IN ('pg_catalog', 'information_schema')
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_row_ver ON %I.%I', r.table_schema, r.table_name);
        EXECUTE format('CREATE TRIGGER trg_row_ver BEFORE UPDATE ON %I.%I FOR EACH ROW EXECUTE FUNCTION %s',
                       r.table_schema, r.table_name,
                       CASE WHEN r.has_updated_at THEN 'util.touch_audit()' ELSE 'util.bump_row_ver()' END);
    END LOOP;
END $$;
