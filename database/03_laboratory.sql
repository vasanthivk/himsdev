     LIMS: test catalogue, samples & barcodes, chain of custody, analyzers & worklists, results, delta/reflex, microbiology & AST, QC/Westgard, calibration, reagents, outsourcing, report release; blood centre: donors, donations, TTI screening, components, crossmatch, issue.
