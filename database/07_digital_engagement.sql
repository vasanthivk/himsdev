/* =====================================================================================
   DR REDDIS HEALTHCARE - HIMS MICROSERVICE DATABASE
   Service      : 07. Digital Engagement
   Database     : hims_digital_engagement   (PostgreSQL 15+ / EDB Postgres Advanced Server / Azure Database for PostgreSQL Flexible Server)
   Derived from : DrReddis_HIMS_Enterprise_Data_Model_PostgreSQL.sql (enterprise logical model)
   -------------------------------------------------------------------------------------
   Responsibility:
     Website/app e-commerce (tests, packages, medicines), teleconsultation sessions, remote monitoring, tele-ECG/pathology/radiology expert requests, AI triage bot, CRM enquiries & follow-ups, campaigns, feedback, medical camps.
   Owned tables  : 14   | Replica / read-model tables in schema ref: 22
   Events PUBLISHED (Azure Service Bus topic 'hims.digital-engagement'):
     OnlineOrderPlaced, OnlineOrderPaid, EnquiryConverted, TeleSessionStarted, TeleSessionEnded, ExpertOpinionReported, CampRegistered, FeedbackReceived
   Events SUBSCRIBED:
     PatientRegistered, AppointmentBooked, LabReportReleased, RadReportFinalised, PrescriptionIssued, BillFinalised, PaymentReceived, ServiceUpdated, PractitionerUpdated
   Rules:
     - Only this service writes to the owned tables below. Other services read via API or events.
     - Foreign keys to data owned by other services are removed and marked 'logical FK'.
       Integrity is enforced by the application (validate id via API / replica at write time).
     - ref.* tables are local, eventually consistent copies filled by event handlers.
       Never write to them from business code; never enforce FKs against them.
     - Every state change writes a row to evt.outbox in the SAME transaction (transactional outbox).
     - Every consumed message is recorded in evt.inbox for idempotent processing.
   ===================================================================================== */

