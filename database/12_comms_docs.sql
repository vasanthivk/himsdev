/* =====================================================================================
   DR REDDIS HEALTHCARE - HIMS MICROSERVICE DATABASE
   Service      : 12. Communication & Documents (platform)
   Database     : hims_comms_docs   (PostgreSQL 15+ / EDB Postgres Advanced Server / Azure Database for PostgreSQL Flexible Server)
   Derived from : DrReddis_HIMS_Enterprise_Data_Model_PostgreSQL.sql (enterprise logical model)
   -------------------------------------------------------------------------------------
   Responsibility:
     Document store index (Blob), report letterheads & PDF rendering, digital signatures, notifications (SMS/WhatsApp/email/push) with templates and delivery tracking.
   Owned tables  : 3   | Replica / read-model tables in schema ref: 3
   Events PUBLISHED (Azure Service Bus topic 'hims.comms-docs'):
     NotificationDelivered, NotificationFailed, DocumentRendered
   Events SUBSCRIBED:
     AppointmentBooked, AppointmentCancelled, LabReportReleased, RadReportFinalised, CriticalValueDetected, BillFinalised, PaymentReceived, DischargeCompleted, CredentialExpiring, BatchNearExpiry, ServiceRequestAssigned
   Rules:
     - Only this service writes to the owned tables below. Other services read via API or events.
     - Foreign keys to data owned by other services are removed and marked 'logical FK'.
       Integrity is enforced by the application (validate id via API / replica at write time).
     - ref.* tables are local, eventually consistent copies filled by event handlers.
       Never write to them from business code; never enforce FKs against them.
     - Every state change writes a row to evt.outbox in the SAME transaction (transactional outbox).
     - Every consumed message is recorded in evt.inbox for idempotent processing.
   ===================================================================================== */

