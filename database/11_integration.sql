/* =====================================================================================
   DR REDDIS HEALTHCARE - HIMS MICROSERVICE DATABASE
   Service      : 11. Integration Hub (platform)
   Database     : hims_integration   (PostgreSQL 15+ / EDB Postgres Advanced Server / Azure Database for PostgreSQL Flexible Server)
   Derived from : DrReddis_HIMS_Enterprise_Data_Model_PostgreSQL.sql (enterprise logical model)
   -------------------------------------------------------------------------------------
   Responsibility:
     Anti-corruption layer to the outside world: FHIR R4 sync with Azure Health Data Services, ABDM (HIP/HIU, care contexts), NHCX claims, HL7 v2/ASTM analyzers, DICOM notifications, payment gateways, IoT device telemetry routing.
   Owned tables  : 3   | Replica / read-model tables in schema ref: 2
   Events PUBLISHED (Azure Service Bus topic 'hims.integration'):
     AnalyzerResultReceived, DicomStudyReceived, VitalsStreamed, AbhaLinked, NhcxResponseReceived, PaymentGatewayCallback
   Events SUBSCRIBED:
     PatientRegistered, PatientUpdated, EncounterClosed, LabReportReleased, RadReportFinalised, PrescriptionIssued, DischargeSummarySigned, ClaimSubmitted, PreauthSubmitted, WorklistRequested
   Rules:
     - Only this service writes to the owned tables below. Other services read via API or events.
     - Foreign keys to data owned by other services are removed and marked 'logical FK'.
       Integrity is enforced by the application (validate id via API / replica at write time).
     - ref.* tables are local, eventually consistent copies filled by event handlers.
       Never write to them from business code; never enforce FKs against them.
     - Every state change writes a row to evt.outbox in the SAME transaction (transactional outbox).
     - Every consumed message is recorded in evt.inbox for idempotent processing.
   ===================================================================================== */

