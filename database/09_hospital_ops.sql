/* =====================================================================================
   DR REDDIS HEALTHCARE - HIMS MICROSERVICE DATABASE
   Service      : 09. Hospital Operations & Quality
   Database     : hims_hospital_ops   (PostgreSQL 15+ / EDB Postgres Advanced Server / Azure Database for PostgreSQL Flexible Server)
   Derived from : DrReddis_HIMS_Enterprise_Data_Model_PostgreSQL.sql (enterprise logical model)
   -------------------------------------------------------------------------------------
   Responsibility:
     Assets & equipment registry, AMC/CMC, maintenance & calibration, housekeeping/fumigation, linen, kitchen menus & meal dispatch, gate pass, complaints, incidents (NABH), quality indicators, policy/SOP document control.
   Owned tables  : 13   | Replica / read-model tables in schema ref: 15
   Events PUBLISHED (Azure Service Bus topic 'hims.hospital-ops'):
     BedCleaned, AssetDown, AssetRestored, MealDispatched, IncidentReported, ComplaintEscalated, CalibrationDue, ClearanceGranted
   Events SUBSCRIBED:
     DischargeCompleted, DietOrdered, FeedbackReceived, GRNPosted, TransfusionReactionReported, CodeBlueRaised, BedStatusChanged
   Rules:
     - Only this service writes to the owned tables below. Other services read via API or events.
     - Foreign keys to data owned by other services are removed and marked 'logical FK'.
       Integrity is enforced by the application (validate id via API / replica at write time).
     - ref.* tables are local, eventually consistent copies filled by event handlers.
       Never write to them from business code; never enforce FKs against them.
     - Every state change writes a row to evt.outbox in the SAME transaction (transactional outbox).
     - Every consumed message is recorded in evt.inbox for idempotent processing.
   ===================================================================================== */

