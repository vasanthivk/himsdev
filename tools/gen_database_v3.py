"""Generates database_v3/ from database_v2/ (which it only reads): the 7 consolidated services in ONE database, himsdev.

Naming convention:  <database>.<schema>.<table>  ->  himsdev.<service>.<schema>_<table>
  e.g. new_hims_identity_org.core.organization -> himsdev.identity_org.core_organization
Each consolidated database becomes one schema (the database name without the new_hims_ prefix); each of its tables, views
and functions gets its old schema as a name prefix (util.touch_audit -> identity_org.util_touch_audit). Everything else
(columns, types, defaults, constraints, indexes, triggers, views, foreign keys) is unchanged.

Usage: python tools/gen_database_v3.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V2, V3 = ROOT / "database_v2", ROOT / "database_v3"
DATABASE = "himsdev"
SERVICES = ["01_identity_org", "02_patient_engagement", "03_clinical_care", "04_diagnostics",
            "05_revenue_finance", "06_operations_supply", "07_integration_comms"]
QUALIFIED = re.compile(r"(?<![\w.])([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\b")


def objects(sql):
    """(schema, name) of every table, view and function the v2 script creates."""
    return set(re.findall(r"CREATE (?:TABLE|VIEW|(?:OR REPLACE )?FUNCTION) (\w+)\.(\w+)", sql))


def main():
    V3.mkdir(exist_ok=True)
    (V3 / "seed").mkdir(exist_ok=True)
    sources = {f: (V2 / f"{f}.sql").read_text(encoding="utf-8") for f in SERVICES}
    service = {f: f[3:] for f in SERVICES}                       # 04_diagnostics -> diagnostics
    local = {f: {o: f"{service[f]}.{o[0]}_{o[1]}" for o in objects(s)} for f, s in sources.items()}
    # tables a service OWNS (not its ref/evt copies or helpers): used to rename cross-service names in comments
    owned = {}
    for f, objs in local.items():
        for (schema, name), new in objs.items():
            if schema not in ("ref", "evt", "util") and (schema, name) != ("core", "number_sequence"):
                owned.setdefault((schema, name), new)

    def rename(text, f):
        def sub(m):
            key = (m.group(1), m.group(2))
            return local[f].get(key) or owned.get(key) or m.group(0)
        return QUALIFIED.sub(sub, text)

    report = []
    for f in SERVICES:
        svc, sql = service[f], sources[f]
        old_schemas = re.findall(r"(?m)^CREATE SCHEMA (\w+);\n\n?", sql)
        # the v2 header (run-once lines + the first /* ==== */ block) is replaced by the v3 header after renaming
        m = re.match(r"\A-- Run once.*?\n\n(/\*\s*=+.*?=+\s*\*/\n)", sql, re.S)
        v2_header, sql = m.group(1), sql[m.end():]
        title = re.search(r"Service\s*:\s*(.+)", v2_header).group(1).strip()
        replaces = re.search(r"Replaces\s*:\s*(.+)", v2_header).group(1).strip()
        # schemas: the old per-database schemas become name prefixes inside one schema per service
        first = True

        def schema_stmt(m):
            nonlocal first
            if first:
                first = False
                return (f"-- One schema for the whole service. Its former schemas ({', '.join(old_schemas)}) are now table-name prefixes.\n"
                        f"CREATE SCHEMA {svc};\n\n")
            return ""
        sql = re.sub(r"(?m)^CREATE SCHEMA \w+;\n\n?", schema_stmt, sql)
        sql = rename(sql, f)
        # the row_ver trigger block: only this service's schema (the database is shared with the other services)
        before = sql
        sql = sql.replace("           AND c.table_schema NOT IN ('pg_catalog', 'information_schema')\n",
                          f"           AND c.table_schema = '{svc}'\n")
        assert sql != before, f"{f}: row_ver block not found"
        rule = "=" * 85
        header = "\n".join([
            f"-- Run once as an admin (all services share it), then connect to it and run this script:",
            f"--   CREATE DATABASE {DATABASE} ENCODING 'UTF8' TEMPLATE template0;", f"--   \\c {DATABASE}", "",
            f"/* {rule}", f"   DR REDDIS HEALTHCARE - HIMS CONSOLIDATED MICROSERVICE SCHEMA (database_v3)",
            f"   Service      : {title}",
            f"   Database     : {DATABASE}   schema: {svc}   (PostgreSQL 15+)",
            f"   Replaces     : database_v2/{f}.sql (database new_hims_{svc}), which replaced {replaces}",
            f"   Generated by : tools/gen_database_v3.py from database_v2/ - regenerate, do not edit this file.",
            f"   {'-' * 85}",
            f"   Naming       : new_hims_{svc}.<schema>.<table>  ->  {DATABASE}.{svc}.<schema>_<table>",
            f"                  e.g. core . number_sequence -> {svc}.core_number_sequence, util . touch_audit() -> {svc}.util_touch_audit()",
            f"   Unchanged    : columns, types, defaults, constraints, indexes, triggers, views and foreign keys of database_v2.",
            f"   Other services' tables live in their own schemas of {DATABASE}; references to them stay logical (no FK), as before.",
            f"   The service's own copies (ref_*), outbox/inbox (evt_*) and helpers (util_*) are in this schema.",
            f"   Part headers below are quoted from the original scripts (their names are updated to the new convention).",
            f"   {rule} */", ""])
        (V3 / f"{f}.sql").write_text(header + "\n" + sql, encoding="utf-8", newline="\n")

        seed = V2 / "seed" / f"{f}.seed.sql"
        if seed.exists():
            (V3 / "seed" / seed.name).write_text(rename(seed.read_text(encoding="utf-8"), f), encoding="utf-8", newline="\n")
        leftover = sorted({m.group(0) for m in QUALIFIED.finditer(re.sub(r"--[^\n]*|/\*.*?\*/", "", sql, flags=re.S))
                           if m.group(1) not in (svc, "information_schema", "pg_catalog")
                           and m.group(1) in {s for s, _ in local[f]} | set(old_schemas)})
        report.append(f"{f}.sql  schema {svc}: {len(local[f])} objects renamed, old schemas {old_schemas}, "
                      f"seed {'yes' if seed.exists() else 'no'}, old names left in code: {leftover or 'none'}")
    print("\n".join(report))


if __name__ == "__main__":
    main()
