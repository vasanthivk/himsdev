-- replica of revenuefinance.bil_receipt, owned by Revenue Cycle; used by: revenuefinance.edu_fee_invoice
-- revenuefinance.ref_bil_receipt was an event-filled replica of revenuefinance.bil_receipt [06. Revenue Cycle]. Both are in this database now, so it is a
-- read-only view of the owner table (same name and columns): the data is stored once and is always current.
CREATE VIEW revenuefinance.ref_bil_receipt AS
SELECT receipt_id,
       branch_id,
       receipt_no,
       receipt_type,
       patient_id,
       encounter_id,
       payer_id,
       counter_code,
       cashier_id,
       receipt_status,
       updated_at,
       updated_by,
       row_ver::BIGINT AS source_version,
       COALESCE(updated_at, created_at) AS replicated_at
  FROM revenuefinance.bil_receipt;

CREATE TRIGGER trg_read_only INSTEAD OF INSERT OR UPDATE OR DELETE ON revenuefinance.ref_bil_receipt
    FOR EACH ROW EXECUTE FUNCTION revenuefinance.util_reject_write();


