CREATE SCHEMA revenuefinance;

-- Rejects writes to the read-only ref.* views (they are kept in step by the owner table itself).
CREATE FUNCTION revenuefinance.util_reject_write() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is a read-only view of a table owned by this service; write to the owner table instead', TG_TABLE_NAME;
END $$;
